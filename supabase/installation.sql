create table if not exists public.tcg_users(name text primary key check(name in ('Anas','Myriam')), salt text not null, hash text not null);
create table if not exists public.tcg_sessions(token text primary key, name text not null references public.tcg_users(name), expires timestamptz not null);
create table if not exists public.tcg_cards(id bigint generated by default as identity primary key,title text not null,caption text not null,rarity integer not null check(rarity between 0 and 4),photo text unique not null);
create table if not exists public.tcg_owned(name text references public.tcg_users(name),card bigint references public.tcg_cards(id),qty integer not null check(qty>=0),primary key(name,card));
create table if not exists public.tcg_days(name text references public.tcg_users(name),day date,opened integer not null default 0,bonus integer not null default 0,primary key(name,day));
create table if not exists public.tcg_messages(id bigint generated by default as identity primary key,name text references public.tcg_users(name),body text not null,created timestamptz not null default now(),bonus integer not null default 0);
create table if not exists public.tcg_trades(id bigint generated by default as identity primary key,sender text references public.tcg_users(name),offered bigint references public.tcg_cards(id),wanted bigint references public.tcg_cards(id),status text not null default 'pending');
create table if not exists public.tcg_login_attempts(key text primary key,count integer not null,until_at timestamptz not null);
create index if not exists tcg_sessions_expiry on public.tcg_sessions(expires);

alter table public.tcg_users enable row level security;
alter table public.tcg_sessions enable row level security;
alter table public.tcg_cards enable row level security;
alter table public.tcg_owned enable row level security;
alter table public.tcg_days enable row level security;
alter table public.tcg_messages enable row level security;
alter table public.tcg_trades enable row level security;
alter table public.tcg_login_attempts enable row level security;
revoke all on public.tcg_users,public.tcg_sessions,public.tcg_cards,public.tcg_owned,public.tcg_days,public.tcg_messages,public.tcg_trades,public.tcg_login_attempts from anon,authenticated;
grant all on public.tcg_users,public.tcg_sessions,public.tcg_cards,public.tcg_owned,public.tcg_days,public.tcg_messages,public.tcg_trades,public.tcg_login_attempts to service_role;
grant usage,select on all sequences in schema public to service_role;

