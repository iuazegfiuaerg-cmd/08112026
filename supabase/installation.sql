create or replace function public.tcg_state(a_name text) returns jsonb language sql security definer set search_path=public as $$
select jsonb_build_object('name',a_name,'partner',case when a_name='Anas' then 'Myriam' else 'Anas' end,
 'day',(now() at time zone 'Europe/Paris')::date::text,'opened',coalesce(d.opened,0),'bonus',coalesce(d.bonus,0),'available',greatest(0,1+coalesce(d.bonus,0)-coalesce(d.opened,0)),
 'cards',coalesce((select jsonb_agg(to_jsonb(c) order by id desc) from tcg_cards c),'[]'::jsonb),
 'owned',coalesce((select jsonb_agg(jsonb_build_object('card',card,'qty',qty)) from tcg_owned where name=a_name and qty>0),'[]'::jsonb),
 'partnerOwned',coalesce((select jsonb_agg(jsonb_build_object('card',card,'qty',qty)) from tcg_owned where name<>a_name and qty>0),'[]'::jsonb),
 'messages',coalesce((select jsonb_agg(to_jsonb(m) order by id) from (select * from tcg_messages order by id desc limit 60)m),'[]'::jsonb),
 'trades',coalesce((select jsonb_agg(to_jsonb(t) order by id desc) from (select * from tcg_trades order by id desc limit 40)t),'[]'::jsonb))
from (select 1)x left join tcg_days d on d.name=a_name and d.day=(now() at time zone 'Europe/Paris')::date;
$$;

create or replace function public.tcg_login_guard(a_key text) returns boolean language plpgsql security definer set search_path=public as $$
declare n integer;
begin
 delete from tcg_login_attempts where until_at<now();
 insert into tcg_login_attempts(key,count,until_at) values(a_key,1,now()+interval '10 minutes')
 on conflict(key) do update set count=tcg_login_attempts.count+1 returning count into n;
 return n<=20;
end;$$;

create or replace function public.tcg_action(a_token text,a_action text,a_body jsonb default '{}'::jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare n text; partner text; today date; d tcg_days%rowtype; t tcg_trades%rowtype; picked bigint; ids jsonb:='[]'::jsonb; i integer; earned integer:=0; offered_id bigint;wanted_id bigint;last_at timestamptz;
begin
 select name into n from tcg_sessions where token=a_token and expires>now();
 if n is null then raise exception '401|Connecte-toi pour continuer.'; end if;
 if a_action='check' then return jsonb_build_object('name',n);end if;
 partner:=case when n='Anas' then 'Myriam' else 'Anas' end;
 today:=(now() at time zone 'Europe/Paris')::date;
 if a_action='state' then return tcg_state(n);end if;
 -- Sérialise les mutations : limites quotidiennes, quantités et échanges atomiques.
 perform pg_advisory_xact_lock(8112025);
 insert into tcg_days(name,day) values(n,today) on conflict do nothing;
 select * into d from tcg_days where name=n and day=today for update;
 if a_action='logout' then delete from tcg_sessions where token=a_token;return jsonb_build_object('ok',true);
 elsif a_action='cards' then
  if length(trim(a_body->>'title')) not between 1 and 60 or length(trim(a_body->>'caption')) not between 1 and 200 or (a_body->>'rarity')::integer not between 0 and 4 then raise exception '400|Vérifie les champs de la carte.';end if;
  insert into tcg_cards(title,caption,rarity,photo) values(trim(a_body->>'title'),trim(a_body->>'caption'),(a_body->>'rarity')::integer,a_body->>'photo');
 elsif a_action='open' then
  if d.opened>=1+d.bonus or d.opened>=3 then raise exception '400|Plus de boosters disponibles aujourd’hui.';end if;
  if not exists(select 1 from tcg_cards) then raise exception '400|Ajoute une première carte.';end if;
  for i in 1..5 loop
   with weighted as(select id,(case rarity when 0 then 60 when 1 then 25 when 2 then 10 when 3 then 4 else 1 end)::double precision/count(*)over(partition by rarity) as weight from tcg_cards)
   select id into picked from weighted order by -ln(greatest(random(),0.000000000001))/weight limit 1;
   insert into tcg_owned(name,card,qty)values(n,picked,1)on conflict(name,card)do update set qty=tcg_owned.qty+1;
   ids:=ids||to_jsonb(picked);
  end loop;
  update tcg_days set opened=opened+1 where name=n and day=today;
  return tcg_state(n)||jsonb_build_object('revealed',ids);
 elsif a_action='message' then
  if length(trim(coalesce(a_body->>'body',''))) not between 1 and 1000 then raise exception '400|Écris un message de 1 à 1 000 caractères.';end if;
  select created into last_at from tcg_messages where name=n order by id desc limit 1;
  if last_at>now()-interval '3 seconds' then raise exception '429|Patiente quelques secondes avant ton prochain message.';end if;
  if d.bonus<2 and (a_body->>'normalized') ~ '(je t aime|je t adore|tu me manques|mon amour|ma cherie|mon cheri|t es magnifique|tu es magnifique|ma vie|mon coeur|bisous|mw+a+h*|❤|💕|💖|💗|💘|🥰|😘)' then earned:=1;update tcg_days set bonus=bonus+1 where name=n and day=today;end if;
  insert into tcg_messages(name,body,bonus)values(n,trim(a_body->>'body'),earned);
 elsif a_action='trade' then
  offered_id:=(a_body->>'offered')::bigint;wanted_id:=(a_body->>'wanted')::bigint;
  if offered_id=wanted_id or not exists(select 1 from tcg_owned where name=n and card=offered_id and qty>0) or not exists(select 1 from tcg_owned where name=partner and card=wanted_id and qty>0) then raise exception '400|Choisis deux cartes différentes disponibles.';end if;
  insert into tcg_trades(sender,offered,wanted)values(n,offered_id,wanted_id);
 elsif a_action='trade-action' then
  select * into t from tcg_trades where id=(a_body->>'id')::bigint and status='pending' for update;
  if not found then raise exception '400|Échange déjà traité.';end if;
  if a_body->>'action'='cancel' and t.sender=n then update tcg_trades set status='cancelled' where id=t.id;return tcg_state(n);end if;
  if t.sender=n then raise exception '403|Seul le destinataire peut accepter cet échange.';end if;
  if a_body->>'action'='decline' then update tcg_trades set status='declined' where id=t.id;return tcg_state(n);end if;
  if (a_body->>'action') is distinct from 'accept' then raise exception '400|Action invalide.';end if;
  if not exists(select 1 from tcg_owned where name=t.sender and card=t.offered and qty>0) or not exists(select 1 from tcg_owned where name=n and card=t.wanted and qty>0) then raise exception '409|Une carte n’est plus disponible.';end if;
  update tcg_owned set qty=qty-1 where name=t.sender and card=t.offered;
  update tcg_owned set qty=qty-1 where name=n and card=t.wanted;
  insert into tcg_owned(name,card,qty) values(n,t.offered,1)on conflict(name,card)do update set qty=tcg_owned.qty+1;
  insert into tcg_owned(name,card,qty) values(t.sender,t.wanted,1)on conflict(name,card)do update set qty=tcg_owned.qty+1;
  update tcg_trades set status='accepted' where id=t.id;
 else raise exception '404|Action inconnue.';
 end if;
 return tcg_state(n);
end;$$;
revoke all on function public.tcg_state(text),public.tcg_action(text,text,jsonb),public.tcg_login_guard(text) from public,anon,authenticated;
grant execute on function public.tcg_state(text),public.tcg_action(text,text,jsonb),public.tcg_login_guard(text) to service_role;
notify pgrst, 'reload schema';

